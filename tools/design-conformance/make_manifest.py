#!/usr/bin/env python3
"""Design conformance: distil the widget boards into `design/conformance/states.json`.

Reads `<out>/inventory.json` and the board renders (`<out>/boards/*.png`, from board_inventory.py)
and writes, for every brick of the boards "States" (dark) and "StatesLight" (light) and every
visible state column, what the toolkit must reproduce:
  * the box of the clickable element (size compared ±2 px at 1x),
  * sample points relative to that box with the board's rendered colour there
    (fill inside the brick, its top border, the focus ring outside it).
The Rust test `platform/ultar-ui/tests/design_conformance.rs` reads this file; it never needs a
browser. Re-run this script whenever a board changes and commit the result.

Usage: make_manifest.py <repo-root> <out-dir> [--check]
With --check nothing is written: the script exits 1 when the committed manifest no longer matches
the boards (geometry ±0.5, colours ±3 per channel – the browser's blending varies by one step).
"""
import json
import pathlib
import re
import sys

from PIL import Image

ROWS = ["primary", "plain", "quiet", "danger", "iconbutton", "switch-off", "switch-on",
        "select", "slider", "textfield", "checkbox", "listitem"]
STATES = ["normal", "hovered", "pressed", "focused", "disabled", "loading", "error"]
# Bricks whose width the board takes from its column, not from the content.
COLUMN_WIDTH = {"slider", "textfield", "checkbox", "listitem"}


def px(im, x, y):
    import math
    x, y = int(math.floor(x)), int(math.floor(y))
    if 0 <= x < im.width and 0 <= y < im.height:
        r, g, b = im.getpixel((x, y))[:3]
        return [r, g, b]
    return None


def samples(row, ab, vis, outline, im, ring_box):
    """Sample points (dx, dy relative to the clickable box) with the board colour."""
    vb = vis["box"] if vis else ab
    out = []
    cy = vb["y"] + vb["h"] / 2
    if row in ("switch-off", "switch-on", "slider"):
        fx = vb["x"] + vb["w"] / 2
    elif row == "checkbox":
        fx = vb["x"] + 4
    else:
        fx = vb["x"] + 5
    if row == "slider":
        cy = vb["y"] + vb["h"] / 2
    pts = [("fill", fx, cy)]
    if vis and float(vis["style"]["bw"].rstrip("px") or 0) > 0 and row not in ("slider",):
        pts.append(("border", vb["x"] + vb["w"] / 2 + (vb["w"] / 4 if row.startswith("switch") else 0), vb["y"] + 0.5))
    if outline:
        off = float(outline.split()[-1].rstrip("px"))
        pts.append(("ring", ring_box["x"] + ring_box["w"] / 2, ring_box["y"] - off - 1))
    pts.append(("ground", ab["x"] - 10, ab["y"] + ab["h"] / 2))
    for what, x, y in pts:
        c = px(im, x, y)
        if c is not None:
            out.append({"what": what, "dx": round(x - ab["x"], 2), "dy": round(y - ab["y"], 2), "rgb": c})
    return out


def main():
    repo = pathlib.Path(sys.argv[1]).resolve()
    out = pathlib.Path(sys.argv[2]).resolve()
    inv = json.loads((out / "inventory.json").read_text())
    cases = []
    for board, theme in (("States", "dark"), ("StatesLight", "light")):
        im = Image.open(out / "boards" / f"{board}.png").convert("RGB")
        acts = inv[board]["acts"]
        assert len(acts) == len(ROWS) * len(STATES), f"{board}: {len(acts)} bricks"
        for i, act in enumerate(acts):
            row, state = ROWS[i // len(STATES)], STATES[i % len(STATES)]
            ab = act["box"]
            if row == "textfield" and act.get("visual"):
                ab = act["visual"]["box"]
            visible = ab["x"] >= 0 and ab["x"] + ab["w"] <= inv[board]["width"]
            vis = act.get("visual")
            outline = act["style"].get("outline") or (vis or {}).get("style", {}).get("outline") or ""
            ring_box = ab if act["style"].get("outline") else (vis or act)["box"]
            cases.append({
                "board": board, "theme": theme, "lang": "ar", "row": row, "state": state,
                "name": act["name"], "visible_on_board": visible,
                "x": ab["x"], "y": ab["y"], "w": ab["w"], "h": ab["h"], "bw": inv[board]["width"], "bh": inv[board]["height"], "fixed_width": row in COLUMN_WIDTH,
                "visual": vis["box"] if vis else None,
                "radius": (vis or act)["style"]["radius"],
                "opacity": float(act["style"]["opacity"]),
                "samples": samples(row, ab, vis, outline, im, ring_box) if visible else [],
            })
    dst = repo / "design/conformance/states.tsv"
    check = "--check" in sys.argv[3:]
    lines = ["# Generated by tools/design-conformance/make_manifest.py from design/boards/project/States*.dc.html.",
             "# board\ttheme\trow\tstate\tvisible\tx\ty\tw\th\tfixed_width\tboard_w\tboard_h\tsamples (what:dx:dy:r,g,b;...)"]
    for c in cases:
        smp = ";".join(f"{s['what']}:{s['dx']}:{s['dy']}:{','.join(map(str, s['rgb']))}" for s in c["samples"])
        lines.append("\t".join([c["board"], c["theme"], c["row"], c["state"], "1" if c["visible_on_board"] else "0",
                                 str(c["x"]), str(c["y"]), str(c["w"]), str(c["h"]), "1" if c["fixed_width"] else "0",
                                 str(c["bw"]), str(c["bh"]), smp or "-"]))
    if check:
        return 0 if same(dst.read_text().splitlines(), lines) else 1
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text("\n".join(lines) + "\n")
    print(f"{dst}: {len(cases)} cases")
    return 0


def same(old, new):
    """True when two manifests agree within the tolerances."""
    def nums(line):
        return [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", line)]
    old = [l for l in old if not l.startswith("#")]
    new = [l for l in new if not l.startswith("#")]
    if len(old) != len(new):
        print(f"states.tsv: {len(old)} cases committed, {len(new)} on the boards")
        return False
    ok = True
    for a, b in zip(old, new):
        ta, tb = re.sub(r"-?\d+(?:\.\d+)?", "#", a), re.sub(r"-?\d+(?:\.\d+)?", "#", b)
        na, nb = nums(a), nums(b)
        if ta != tb or len(na) != len(nb) or any(abs(x - y) > 3 for x, y in zip(na, nb)):
            print(f"states.tsv differs from the boards:\n  committed {a}\n  boards    {b}")
            ok = False
    return ok


if __name__ == "__main__":
    sys.exit(main())
