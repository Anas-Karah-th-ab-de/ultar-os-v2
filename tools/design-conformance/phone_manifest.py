#!/usr/bin/env python3
"""Design conformance of the phone app: distil the boards PhoneDial, PhoneIncoming and
PhoneInCall into `design/conformance/phone.tsv`.

For every clickable element (`data-act`) of the three boards it records the box of what is
painted (the element itself, or its painted container such as the number field), and the board
colour at two sample points of that box: `fill` (5 points in from the start edge, middle height)
and `border` (middle of the top edge) when the element has a border. The Rust test
`apps/ultar-phone/tests/design_conformance.rs` rebuilds the boards with the app and compares
(size ±1 point, colours ±16 per channel); no browser is needed there.

Usage: phone_manifest.py <repo-root> <out-dir> [--check]
<out-dir> holds inventory.json and boards/*.png from board_inventory.py. With --check nothing is
written; exit 1 when the committed manifest no longer matches the boards.
"""
import json
import math
import pathlib
import re
import sys

from PIL import Image

BOARDS = ["PhoneDial", "PhoneIncoming", "PhoneInCall"]


def px(im, x, y):
    x, y = int(math.floor(x)), int(math.floor(y))
    if 0 <= x < im.width and 0 <= y < im.height:
        return list(im.getpixel((x, y))[:3])
    return None


def rows(repo, out):
    inv = json.loads((out / "inventory.json").read_text())
    lines = []
    for board in BOARDS:
        im = Image.open(out / "boards" / f"{board}.png").convert("RGB")
        rtl = inv[board]["dir"] == "rtl"
        for act in inv[board]["acts"]:
            vis = act.get("visual")
            box = vis["box"] if vis and not vis["self"] else act["box"]
            style = vis["style"] if vis else act["style"]
            samples = []
            # fill: 5 points in from the start edge (right in Arabic), middle height
            fx = box["x"] + box["w"] - 5 if rtl else box["x"] + 5
            painted = style["bg"] not in ("rgba(0, 0, 0, 0)", "transparent")
            if painted:
                samples.append(("fill", fx - box["x"], box["h"] / 2))
            if float(style["bw"].rstrip("px") or 0) > 0 and style["border"] not in ("rgba(0, 0, 0, 0)",):
                samples.append(("border", box["w"] / 2, 0.5))
            smp = []
            for what, dx, dy in samples:
                c = px(im, box["x"] + dx, box["y"] + dy)
                if c is not None:
                    smp.append(f"{what}:{round(dx, 2)}:{round(dy, 2)}:{','.join(map(str, c))}")
            lines.append("\t".join([board, str(act["i"]), act["act"], act["name"],
                                    str(box["x"]), str(box["y"]), str(box["w"]), str(box["h"]),
                                    ";".join(smp) or "-"]))
    return lines


def same(old, new):
    def nums(line):
        return [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", line)]
    old = [l for l in old if l and not l.startswith("#")]
    new = [l for l in new if l and not l.startswith("#")]
    if len(old) != len(new):
        print(f"phone.tsv: {len(old)} rows committed, {len(new)} on the boards")
        return False
    ok = True
    for a, b in zip(old, new):
        if a.split("\t")[:4] != b.split("\t")[:4] or any(abs(x - y) > 3 for x, y in zip(nums(a), nums(b))):
            print(f"phone.tsv differs from the boards:\n  committed {a}\n  boards    {b}")
            ok = False
    return ok


def main():
    repo = pathlib.Path(sys.argv[1]).resolve()
    out = pathlib.Path(sys.argv[2]).resolve()
    head = ["# Generated by tools/design-conformance/phone_manifest.py from design/boards/project/Phone*.dc.html.",
            "# board\tindex\taction\tname\tx\ty\tw\th\tsamples (what:dx:dy:r,g,b;...)"]
    lines = rows(repo, out)
    dst = repo / "design/conformance/phone.tsv"
    if "--check" in sys.argv[3:]:
        return 0 if same(dst.read_text().splitlines(), lines) else 1
    dst.write_text("\n".join(head + lines) + "\n")
    print(f"{dst}: {len(lines)} elements")
    return 0


if __name__ == "__main__":
    sys.exit(main())
