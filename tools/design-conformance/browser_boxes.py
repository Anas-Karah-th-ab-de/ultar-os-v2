#!/usr/bin/env python3
"""Board side of the browser window's conformance (apps/ultar-web/tests/design_conformance.rs).

Writes (or with --check compares) apps/ultar-web/tests/fixtures/browser-board.tsv: every
`browser.*` element of the board "DesktopBottom" with its box relative to the window's
client area (the section "Ultar Browser" minus its 1-pixel border and the 40-point title
bar the compositor draws), its visual box (painted background/border) and colours.

Usage: browser_boxes.py <repo-root> <inventory.json> [--check]
"""
import json
import pathlib
import sys

HEADER = "# Generated by tools/design-conformance/browser_boxes.py from design/boards/project/DesktopBottom.dc.html.\n" \
         "# act\tname\tx\ty\tw\th\tvx\tvy\tvw\tvh\tbg\tborder\tfg\tdisabled\n"


def rows(inventory):
    board = inventory["DesktopBottom"]
    section = next(r for r in board["regions"] if r["tag"] == "section" and r["name"] == "Ultar Browser")
    ox, oy = section["box"]["x"] + 1, section["box"]["y"] + 1 + 40
    out = []
    for a in board["acts"]:
        if not a["act"].startswith("browser."):
            continue
        b = a["box"]
        v = (a["visual"] or {}).get("box") or b
        st = (a["visual"] or {}).get("style") or a["style"]
        out.append("\t".join(str(x) for x in [
            a["act"], a["name"], round(b["x"] - ox, 2), round(b["y"] - oy, 2), b["w"], b["h"],
            round(v["x"] - ox, 2), round(v["y"] - oy, 2), v["w"], v["h"],
            st["bg"], st["border"], a["style"]["fg"], int(a["disabled"])]))
    return HEADER + "\n".join(out) + "\n"


def main():
    repo = pathlib.Path(sys.argv[1])
    text = rows(json.loads(pathlib.Path(sys.argv[2]).read_text()))
    path = repo / "apps/ultar-web/tests/fixtures/browser-board.tsv"
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != text:
            print(f"{path} is stale: run tools/design-conformance/browser_boxes.py", file=sys.stderr)
            sys.exit(1)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


if __name__ == "__main__":
    main()
