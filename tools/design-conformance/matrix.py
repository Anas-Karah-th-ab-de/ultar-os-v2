#!/usr/bin/env python3
"""Coverage matrix: board -> element -> status, from the board inventory and coverage.toml.

Usage: matrix.py <repo-root> <inventory.json> <out.md>
Status per clickable element comes from design/conformance/coverage.toml (by action); landmark
regions take the status of the surface (`surface` table at the end of coverage.toml if present,
otherwise MISSING when every action of the board is missing).
"""
import json
import pathlib
import re
import sys
import tomllib

LABEL = {"ok": "OK", "different": "DIFFERENT", "missing": "MISSING", "dead": "DEAD CLICK", "na": "n/a (off-board)"}
ROWS = ["primary", "plain", "quiet", "danger", "iconbutton", "switch-off", "switch-on",
        "select", "slider", "textfield", "checkbox", "listitem"]
STATES = ["normal", "hovered", "pressed", "focused", "disabled", "loading", "error"]


def brick_status(board, index, known):
    """Status of one brick of the States boards from the known differences."""
    row, state = ROWS[index // 7], STATES[index % 7]
    if state == "error":
        return "na", f"{row}/{state}: error column lies outside the artboard"
    diffs = sorted(k.split(": ", 1)[1] for k in known if k.startswith(f"{board}/{row}/{state}:"))
    if diffs:
        return "different", f"{row}/{state}: " + ", ".join(diffs)
    return "ok", f"{row}/{state}"


def main():
    repo = pathlib.Path(sys.argv[1])
    inv = json.loads(pathlib.Path(sys.argv[2]).read_text())
    cov = tomllib.loads((repo / "design/conformance/coverage.toml").read_text())["action"]
    known = {l.strip() for l in (repo / "design/conformance/known-differences.txt").read_text().splitlines()
             if l.strip() and not l.startswith("#")}
    ftl = "".join(p.read_text() for p in repo.glob("**/locales/ar.ftl") if "target" not in p.parts)
    arabic = re.compile("[؀-ۿ]")
    out = ["# Design conformance – coverage matrix (generated by tools/design-conformance/matrix.py)", "",
           "Status per clickable element from `design/conformance/coverage.toml`; `cat.` = share of the board's",
           "Arabic text runs found verbatim in a `locales/ar.ftl` of the repo (catalog readiness).", ""]
    summary = []
    for board, d in inv.items():
        acts = d["acts"]
        counts = {k: 0 for k in LABEL}
        rows = []
        for a in acts:
            e = dict(cov.get(a["act"], {"status": "missing", "impl": "", "note": "not in coverage.toml"}))
            if board in ("States", "StatesLight") and a["act"] == "demo":
                e["status"], e["impl"] = brick_status(board, a["i"] - 1, known)
            counts[e["status"]] += 1
            name = a["name"].replace("|", "/")[:48]
            flags = []
            if a["disabled"]:
                flags.append("disabled")
            if a["box"]["x"] + a["box"]["w"] <= 0:
                flags.append("off-board")
            rows.append(f"| {a['i']} | {name} | `{a['act']}` | {' '.join(flags)} | {LABEL[e['status']]} | "
                        f"{e.get('impl') or '–'} |")
        texts = {t["text"] for t in d["texts"] if arabic.search(t["text"]) and len(t["text"]) > 2}
        found = sum(1 for t in texts if t in ftl)
        total = len(acts)
        done = counts["ok"] + 0.5 * counts["different"]
        total -= counts["na"]
        pct = 100.0 * done / total if total else 0.0
        summary.append((board, d["width"], d["height"], d["dir"], total, counts, pct, found, len(texts),
                        len(d["icons"]), len([r for r in d["regions"] if r["role"] or r["name"]])))
        out.append(f"## {board} ({d['width']}×{d['height']}, {d['dir']}, {total} clickable)")
        out.append("")
        regions = [r for r in d["regions"] if (r["role"] or r["name"]) and r["box"]["w"] > 0]
        if regions:
            out.append("Regions: " + "; ".join(sorted({f"{r['role'] or r['tag']} “{r['name'][:30]}”" for r in regions})[:40]))
            out.append("")
        out.append("| # | Element (accessible name) | Action | Flags | Status | Implementation |")
        out.append("|---|---|---|---|---|---|")
        out.extend(rows)
        out.append("")
    head = ["## Totals per board", "",
            "| Board | Size | Dir | Clickable | OK | DIFFERENT | MISSING | DEAD | % complete* | Arabic texts in catalogs | Icons | Regions |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for b, w, h, dr, total, c, pct, found, nt, ni, nr in summary:
        head.append(f"| {b} | {w}×{h} | {dr} | {total} | {c['ok']} | {c['different']} | {c['missing']} | {c['dead']} | "
                    f"{pct:.0f}%{' (+%d n/a)' % c['na'] if c['na'] else ''} | {found}/{nt} | {ni} | {nr} |")
    allc = sum(s[4] for s in summary)  # comparable elements (off-board ones excluded)
    ok = sum(s[5]["ok"] for s in summary)
    diff = sum(s[5]["different"] for s in summary)
    head.append(f"| **all** | | | {allc} | {ok} | {diff} | {allc - ok - diff} | 0 | {100 * (ok + diff / 2) / allc:.1f}% | | | |")
    head.append("")
    head.append("\\* OK counts 1, DIFFERENT ½ (works, but does not look/behave as drawn), MISSING/DEAD 0.")
    head.append("")
    pathlib.Path(sys.argv[3]).write_text("\n".join(out[:5] + head + out[5:]) + "\n")
    print("\n".join(head))


if __name__ == "__main__":
    main()
