//! Driver class and origin as spelled in manifests.

use std::fmt;

macro_rules! text_enum {
    ($(#[$doc:meta])* $name:ident { $($(#[$vdoc:meta])* $variant:ident => $text:literal),* $(,)? }) => {
        $(#[$doc])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub enum $name {
            $($(#[$vdoc])* $variant),*
        }

        impl $name {
            /// Every value, in declaration order.
            pub const ALL: &'static [Self] = &[$(Self::$variant),*];

            /// The spelling used in manifests.
            pub fn as_str(self) -> &'static str {
                match self {
                    $(Self::$variant => $text),*
                }
            }

            /// Parses the manifest spelling.
            pub fn parse(text: &str) -> Option<Self> {
                match text {
                    $($text => Some(Self::$variant),)*
                    _ => None,
                }
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(self.as_str())
            }
        }
    };
}

text_enum! {
    /// Functional class of a driver.
    DriverClass {
        /// Display controllers and panels.
        Display => "display",
        /// Keyboards, pointers, touch.
        Input => "input",
        /// Sound devices.
        Audio => "audio",
        /// Wired network.
        Net => "net",
        /// Wireless LAN.
        Wifi => "wifi",
        /// Bluetooth controllers.
        Bluetooth => "bluetooth",
        /// Disks and storage controllers.
        Storage => "storage",
        /// Cellular modems.
        Modem => "modem",
        /// Cameras.
        Camera => "camera",
        /// Sensors (motion, light, thermal …).
        Sensor => "sensor",
        /// Platform devices (ACPI, power, embedded controller).
        Platform => "platform",
        /// Bus controllers (USB hosts, I2C, SMBus …).
        Bus => "bus",
        /// Security devices (TPM, fingerprint).
        Security => "security",
        /// Anything else.
        Other => "other",
    }
}

text_enum! {
    /// Where a driver comes from.
    Origin {
        /// Written by hand.
        Hand => "hand",
        /// Generated by the driver workshop from a blueprint.
        Workshop => "workshop",
        /// Supplied by the hardware vendor.
        Vendor => "vendor",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn spellings_round_trip() {
        assert_eq!(DriverClass::ALL.len(), 14);
        assert_eq!(Origin::ALL.len(), 3);
        for class in DriverClass::ALL {
            assert_eq!(DriverClass::parse(class.as_str()), Some(*class));
            assert_eq!(class.to_string(), class.as_str());
        }
        for origin in Origin::ALL {
            assert_eq!(Origin::parse(origin.as_str()), Some(*origin));
            assert_eq!(origin.to_string(), origin.as_str());
        }
        assert_eq!(DriverClass::parse("netz"), None);
        assert_eq!(Origin::parse("linux-modul"), None);
        assert_eq!(DriverClass::Bluetooth.as_str(), "bluetooth");
        assert!(DriverClass::Display < DriverClass::Other);
    }
}
